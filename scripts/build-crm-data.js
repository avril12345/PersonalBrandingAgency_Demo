// Bundles data/*.json into crm/data.js so the CRM opens straight from disk
// (browsers block fetch() on file:// URLs). Usage: node scripts/build-crm-data.js
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, "data", f), "utf8"));

const bundle = {
  ...read("clients.json"),
  ...read("team.json"),
  metrics: read("metrics-history.json"),
  today: read("content-calendar.json").generated_for,
  posts: read("content-calendar.json").posts,
  visibility: read("visibility.json").items,
  activity: read("activity.json").entries,
};
fs.writeFileSync(
  path.join(root, "crm", "data.js"),
  "// Generated by scripts/build-crm-data.js — do not edit by hand.\nwindow.LOUD_DATA = " + JSON.stringify(bundle) + ";\n"
);
console.log("Wrote crm/data.js");
